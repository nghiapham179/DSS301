def translate(risk: str, maint: str) -> tuple[str, str]:
    return _VN_RISK.get(risk, risk), _VN_MAINT.get(maint, maint)


def risk_score_estimate(battery: float, wind: float,
                         signal: float, temp: float) -> float:
    """Weighted estimate of risk score 0–10 for display on Prediction page."""
    return min(10.0, round(
        (1 - battery / 100) * 4.0
        + (wind / 50)        * 3.0
        + (1 - signal / 100) * 2.0
        + (abs(temp) / 50)   * 1.0,
        1,
    ))


def save_custom(drone_id: str, inp: pd.DataFrame,
                risk: str, maint: str, rec: str,
                bat_label: str, status: str, reason: str) -> pd.DataFrame:
    """
    Append prediction result to custom_drone_data.csv.
    Saved columns follow README Section 12 exactly (18 columns):
      drone_id, battery_level, flight_time, signal_strength, temperature,
      wind_speed, gps_accuracy, altitude, speed, humidity, pressure,
      operation_risk, maintenance_action, recommendation,
      battery_status, flight_status, flight_reason, created_at

    Fix for README Section 13-Error4:
      Handles empty file gracefully — does not raise EmptyDataError.
    """
    row = inp.copy()
    row.insert(0, "drone_id", drone_id)
    # Prediction columns (README Section 12)
    row["operation_risk"]     = risk
    row["maintenance_action"] = maint
    row["recommendation"]     = rec
    row["battery_status"]     = bat_label
    row["flight_status"]      = status
    row["flight_reason"]      = reason
    row["created_at"]         = pd.Timestamp.now().strftime("%Y-%m-%d %H:%M:%S")

    CUSTOM_DATA_PATH.parent.mkdir(parents=True, exist_ok=True)

    # README Section 13-Error4: safe append — handle empty / missing file
    if CUSTOM_DATA_PATH.exists() and CUSTOM_DATA_PATH.stat().st_size > 0:
        try:
            old = pd.read_csv(CUSTOM_DATA_PATH)
            if not old.empty:
                row = pd.concat([old, row], ignore_index=True)
        except (pd.errors.EmptyDataError, Exception):
            # File exists but is corrupt / truly empty → start fresh
            pass

    row.to_csv(CUSTOM_DATA_PATH, index=False, encoding="utf-8-sig")
    return row


def style_chart(fig: go.Figure, height: int = None) -> go.Figure:
    """Unified Plotly theme — Inter font, near-transparent grid, no frame."""
    fig.update_layout(
        template="plotly_white",
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        font=dict(color="#64697a", family="Inter, system-ui, sans-serif", size=12),
        margin=dict(t=28, b=16, l=12, r=12),
        legend=dict(
            bgcolor="rgba(255,255,255,.8)",
            bordercolor="rgba(0,0,0,.06)",
            borderwidth=1,
            font=dict(color="#1c1e2e", size=11),
        ),
        **({"height": height} if height else {}),
    )
    fig.update_xaxes(gridcolor="rgba(0,0,0,.04)", zerolinecolor="rgba(0,0,0,.04)",
                     linecolor="rgba(0,0,0,.08)")
    fig.update_yaxes(gridcolor="rgba(0,0,0,.04)", zerolinecolor="rgba(0,0,0,.04)",
                     linecolor="rgba(0,0,0,.08)")
    return fig


def make_radar_chart(params: dict, safe_threshold: float = 0.6) -> go.Figure:
    """
    Radar chart comparing current normalised values vs safe threshold.
    params: {label: value_0_to_1}
    """
    labels = list(params.keys())
    vals   = [round(v, 3) for v in params.values()]
    # Close the polygon
    labels_c = labels + [labels[0]]
    vals_c   = vals + [vals[0]]
    thresh_c = [safe_threshold] * len(labels_c)

    fig = go.Figure()
    fig.add_trace(go.Scatterpolar(
        r=thresh_c, theta=labels_c,
        fill="toself", fillcolor="rgba(22,163,74,.08)",
        line=dict(color="rgba(22,163,74,.4)", width=1.5, dash="dot"),
        name="Ngưỡng an toàn",
    ))
    fig.add_trace(go.Scatterpolar(
        r=vals_c, theta=labels_c,
        fill="toself", fillcolor="rgba(79,99,210,.15)",
        line=dict(color="#4f63d2", width=2.5),
        name="Thông số hiện tại",
        marker=dict(size=6, color="#4f63d2"),
    ))
    fig.update_layout(
        polar=dict(
            bgcolor="rgba(0,0,0,0)",
            radialaxis=dict(visible=True, range=[0, 1],
                            tickfont=dict(size=9, color="#9da3b5"),
                            gridcolor="rgba(0,0,0,.06)", linecolor="rgba(0,0,0,.08)"),
            angularaxis=dict(tickfont=dict(size=10, color="#1c1e2e"),
                             gridcolor="rgba(0,0,0,.06)", linecolor="rgba(0,0,0,.08)"),
        ),
        legend=dict(font=dict(size=11, color="#64697a"), bgcolor="rgba(0,0,0,0)",
                    orientation="h", y=-0.15),
        margin=dict(t=24, b=50, l=40, r=40),
        height=340,
        paper_bgcolor="rgba(0,0,0,0)",
        font=dict(family="Inter, system-ui"),
    )
    return fig


