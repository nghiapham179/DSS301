def build_input_df(**kw) -> pd.DataFrame:
    """Build a single-row DataFrame from keyword args (must match FEATURES)."""
    return pd.DataFrame([{k: kw[k] for k in FEATURES}])


def predict_drone(inp: pd.DataFrame) -> tuple[str, str, str, float]:
    """
    Run all 3 classifiers.
    Returns (operation_risk, maintenance_action, recommendation, confidence%).
    README Section 10.
    """
    X = inp[FEATURES]
    rf_r,  le_r  = models["risk"]
    rf_m,  le_m  = models["maint"]
    rf_rc, le_rc = models["rec"]

    risk  = le_r.inverse_transform(rf_r.predict(X))[0]
    maint = le_m.inverse_transform(rf_m.predict(X))[0]
    rec   = le_rc.inverse_transform(rf_rc.predict(X))[0]

    conf = 0.0
    if hasattr(rf_r, "predict_proba"):
        conf = round(float(rf_r.predict_proba(X).max()) * 100, 1)

    return risk, maint, rec, conf


def flight_decision(battery: float, signal: float, wind: float, gps: float,
                    flight_time: float, temp: float, alt: float, speed: float,
                    risk: str, maint: str) -> tuple[str, str, str]:
    """
    Rule-based flight status layer on top of ML predictions.
    Thresholds from README Section 11 (Risk Conditions table) — exact match.

    Returns (flight_status_label, reason_text, alert_level).

    Priority order (most severe first):
      1. Cấm Bay          — hard safety limits exceeded
      2. Yêu Cầu Bảo Trì — model predicted maintenance needed
      3. Quay Về Trạm     — model predicted High risk
      4. Bay Kèm Giám Sát — soft monitoring thresholds exceeded
      5. Đủ Điều Kiện Bay — all clear
    """
    ml = str(maint).lower()

    # ── Level 1: Cấm Bay (README Section 11 — dangerous conditions) ──
    reasons_critical = []
    if battery < 20:
        reasons_critical.append("pin dưới 20%")
    if signal < 35:
        reasons_critical.append("tín hiệu dưới 35%")
    if wind > 35:
        reasons_critical.append("gió trên 35 m/s")
    if gps > 10:
        reasons_critical.append("GPS accuracy trên 10 m")
    if temp > 45:
        reasons_critical.append("nhiệt độ trên 45°C")
    if temp < -10:
        reasons_critical.append("nhiệt độ dưới -10°C")

    if reasons_critical:
        reason = "Điều kiện nguy hiểm: " + ", ".join(reasons_critical) + "."
        return "Cấm Bay", reason, "danger"

    # ── Level 2: Yêu Cầu Bảo Trì ──────────────────────────────────────
    if any(kw in ml for kw in ("maintenance required", "inspection recommended", "inspect", "urgent")):
        return (
            "Yêu Cầu Bảo Trì",
            "Drone cần kiểm tra hoặc bảo trì trước chuyến bay tiếp theo.",
            "danger",
        )

    # ── Level 3: Quay Về Trạm ──────────────────────────────────────────
    if risk == "High":
        return (
            "Quay Về Trạm",
            "Rủi ro vận hành cao. Drone nên quay về trạm để kiểm tra.",
            "warning",
        )

    # ── Level 4: Bay Kèm Giám Sát (README Section 11 — monitoring thresholds) ──
    reasons_monitor = []
    if flight_time > 40:
        reasons_monitor.append("thời gian bay trên 40 phút")
    if alt > 350:
        reasons_monitor.append("độ cao trên 350 m")
    if speed > 75:
        reasons_monitor.append("tốc độ trên 75")
    if battery < 40:
        reasons_monitor.append("pin dưới 40%")
    if signal < 60:
        reasons_monitor.append("tín hiệu dưới 60%")
    if wind > 25:
        reasons_monitor.append("gió trên 25 m/s")
    if gps > 7:
        reasons_monitor.append("GPS accuracy trên 7 m")

    if reasons_monitor:
        reason = "Cần theo dõi sát: " + ", ".join(reasons_monitor) + "."
        return "Bay Kèm Giám Sát", reason, "warning"

    # ── Level 5: Đủ Điều Kiện Bay ──────────────────────────────────────
    return "Đủ Điều Kiện Bay", "Drone đủ điều kiện vận hành bình thường.", "success"


def battery_status(level: float) -> tuple[str, str]:
    """(label, alert_level). README Section 11 thresholds."""
    if level > 40:
        return "Tốt", "success"
    if level > 20:
        return "Trung Bình", "warning"
    return "Yếu", "danger"


def risk_to_level(risk: str) -> str:
    return {"High": "danger", "Medium": "warning", "Low": "success"}.get(risk, "info")


