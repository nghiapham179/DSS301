@st.cache_resource
def load_models() -> dict:
    """Load all 3 RF models + label encoders. README Section 8."""
    names = {
        "risk":  "operation_risk_model",
        "maint": "maintenance_action_model",
        "rec":   "recommendation_model",
    }
    return {
        key: (
            joblib.load(MODEL_DIR / f"{name}.joblib"),
            joblib.load(MODEL_DIR / f"{name}_label_encoder.joblib"),
        )
        for key, name in names.items()
    }


@st.cache_data
def load_data() -> pd.DataFrame:
    """Load drone_data_clean.csv. README Section 4."""
    return pd.read_csv(DATA_PATH)


@st.cache_data
def load_metrics(model_name: str) -> dict | None:
    """Load _metrics.json generated by train_model.py (extended output)."""
    path = MODEL_DIR / f"{model_name}_metrics.json"
    if not path.exists():
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


@st.cache_data
def load_feature_importance() -> pd.DataFrame | None:
    """Load feature_importance.csv generated by train_model.py (extended output)."""
    path = MODEL_DIR / "feature_importance.csv"
    if not path.exists():
        return None
    return pd.read_csv(path)


